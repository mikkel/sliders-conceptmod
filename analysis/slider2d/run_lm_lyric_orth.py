MARKS = {"divergent": "o", "close": "s"}


def _f(value, spec: str = ".3f", empty: str = "N/A") -> str:
    if value is None:
        return empty
    return format(float(value), spec)


def _hit(flag: bool) -> str:
    return "**HIT**" if flag else "MISS"


def plot_lyric_orth(table: dict[str, list[dict]], path: Path) -> None:
    """lyric_recall vs gender_move. Want-box is high both."""
    fig, ax = plt.subplots(figsize=(8.8, 5.8))
    want = Rectangle(
        (LYRIC_RECALL_MIN, GENDER_MOVE_MIN),
        1.0 - LYRIC_RECALL_MIN,
        1.0 - GENDER_MOVE_MIN,
        facecolor="#d5f5e3",
        edgecolor="#1e8449",
        lw=1.0,
        alpha=0.55,
        zorder=1,
        label="want-box (grit lyric HIT AND gender_move HIT)",
    )
    ax.add_patch(want)
    for cell, rows in table.items():
        for row in rows:
            ax.scatter(
                [row["lyric_recall"]],
                [row["gender_move"]],
                c=[COLORS.get(row["name"], "#7f8c8d")],
                marker=MARKS.get(cell, "o"),
                s=90 if row["name"].startswith("faithful_plus_neu") else 64,
                zorder=3,
                edgecolors="#1c2833",
                linewidths=0.7,
            )
            ax.annotate(
                f"{row['name']}\n{cell}",
                (row["lyric_recall"], row["gender_move"]),
                fontsize=6.2,
                xytext=(5, 4),
                textcoords="offset points",
            )
    for name, color in COLORS.items():
        ax.scatter([], [], c=color, marker="o", s=58, label=name)
    ax.axvline(LYRIC_RECALL_MIN, color="#7f8c8d", ls=":", lw=0.9)
    ax.axhline(GENDER_MOVE_MIN, color="#7f8c8d", ls=":", lw=0.9)
    ax.set_xlabel("lyric_recall @ +1  [0, 1]  (higher is better)")
    ax.set_ylabel("gender_move @ +1  [0, 1]  (higher is better)")
    ax.set_title(
        "UNI last-delta / lyric-span projection\n"
        "lyric_recall vs gender_move — not whole-prefix hold, not lyric-token hold"
    )
    ax.set_xlim(-0.02, 1.05)
    ax.set_ylim(-0.02, 1.05)
    ax.grid(alpha=0.25)
    ax.legend(fontsize=6.8, loc="lower left")
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


