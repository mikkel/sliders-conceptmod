def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--steps", type=int, default=400)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    table = lyric_exam_table(steps=args.steps, seed=args.seed)
    verdict = lyric_verdict(table)
    ranked = lyric_rank(table)
    blob = {
        "scale": "plus+neu last-delta / lyric-span projection",
        "not_the_bipolar_board": True,
        "not_prefix_hold": True,
        "not_lyric_token_hold": True,
        "scored": ["lyric_recall", "cover", "neu_hold", "gender_move"],
        "not_scored": ["exam_score", "leak_frac", "c+", "p%"],
        "gates": {
            "lyric_recall_min": LYRIC_RECALL_MIN,
            "cover_min": PLUS_COVER_MIN,
            "neu_hold_min": PLUS_NEU_HOLD_MIN,
            "gender_move_min": GENDER_MOVE_MIN,
            "continuation_floor": EXAM_ROLL_OVERLAP,
        },
        "recipes": [c["name"] for c in LYRIC_RECIPES],
        "cells": list(LYRIC_CELLS),
        "steps": args.steps,
        "seed": args.seed,
        "verdict": {
            k: v
            for k, v in verdict.items()
            if k not in {"last_hidden_blind", "existing_ood"}
        },
        "rank": ranked,
        "rows": table,
    }
    (args.out / "metrics.json").write_text(
        json.dumps(blob, indent=2, default=str) + "\n", encoding="utf-8"
    )
    plot_lyric_orth(table, args.out / "lyric-orth-scale.png")
    write_markdown(table, verdict, ranked, _REPO / "docs" / "lm-lyric-orth.md")
    print(
        f"wrote {args.out}  orth_beats_split={verdict.get('orth_beats_split')} "
        f"want_box={any(r.get('want_box') for r in ranked if r['name']=='faithful_plus_neu_orth')}"
    )


if __name__ == "__main__":
    main()
