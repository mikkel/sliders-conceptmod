def _f(value, spec: str = ".3f", empty: str = "N/A") -> str:
    if value is None:
        return empty
    return format(float(value), spec)


def plot_plus_neu_scale(table: dict[str, list[dict]], path: Path) -> None:
    """cover vs neu_hold. Size/color = off-caption. Want-box is high both."""
    fig, ax = plt.subplots(figsize=(8.6, 5.6))
    marks = {"divergent": "o", "close": "s", "unused_e": "^"}
    colors = {
        "faithful_plus_neu": "#1e8449",
        "faithful_plus": "#7d3c98",
        "leftover_gate_bipolar": "#2471a3",
        "faithful_even_blend": "#b9770e",
        "pair_odd_midpoint": "#c0392b",
    }
    want = Rectangle(
        (PLUS_COVER_MIN, PLUS_NEU_HOLD_MIN),
        1.0 - PLUS_COVER_MIN,
        1.0 - PLUS_NEU_HOLD_MIN,
        facecolor="#d5f5e3",
        edgecolor="#1e8449",
        lw=1.0,
        alpha=0.55,
        zorder=1,
        label="want-box (high cover AND high neu_hold)",
    )
    ax.add_patch(want)
    for cell, rows in table.items():
        if cell == "unused_e":
            continue
        for row in rows:
            off = max(0.0, float(row["off_caption"]))
            size = 70 + 520 * min(1.0, off / 0.12)
            ax.scatter(
                [row["cover"]],
                [row["neu_hold"]],
                c=[off],
                cmap="YlOrRd",
                vmin=0.0,
                vmax=max(PLUS_OFF_MAX, 0.12),
                marker=marks.get(cell, "o"),
                s=size,
                zorder=3,
                edgecolors=colors.get(row["name"], "#7f8c8d"),
                linewidths=1.2,
            )
            ax.annotate(
                f"{row['name']}\n{cell}",
                (row["cover"], row["neu_hold"]),
                fontsize=6.2,
                xytext=(5, 4),
                textcoords="offset points",
            )
    for name, color in colors.items():
        ax.scatter([], [], c=color, marker="o", s=58, label=name)
    ax.axvline(PLUS_COVER_MIN, color="#7f8c8d", ls=":", lw=0.9)
    ax.axhline(PLUS_NEU_HOLD_MIN, color="#7f8c8d", ls=":", lw=0.9)
    ax.set_xlabel("cover of the + state  [0, 1]  (higher is better)")
    ax.set_ylabel("neu_hold at scale 0  [0, 1]  (higher is better)")
    ax.set_title(
        "Plus+neu scale — not the bipolar board\n"
        "cover vs neu_hold; marker size/color = off-caption on +"
    )
    ax.set_xlim(-0.02, 1.05)
    ax.set_ylim(-0.02, 1.05)
    ax.grid(alpha=0.25)
    cbar = fig.colorbar(
        plt.cm.ScalarMappable(
            cmap="YlOrRd",
            norm=plt.Normalize(vmin=0.0, vmax=max(PLUS_OFF_MAX, 0.12)),
        ),
        ax=ax,
        fraction=0.046,
        pad=0.04,
    )
    cbar.set_label("off-caption on the + continuation (lower is better)")
    ax.legend(fontsize=7.0, loc="lower left")
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def _train_label(row: dict) -> str:
    if row.get("plus_neu"):
        return "plus+neu"
    if row.get("plus_only"):
        return "plus-only"
    return "bipolar ±"


