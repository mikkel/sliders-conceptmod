def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--steps", type=int, default=400)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    table = plus_neu_exam_table(steps=args.steps, seed=args.seed)
    verdict = plus_neu_helps(table)
    ranked = plus_neu_rank(table)
    blob = {
        "scale": "plus+neu",
        "not_the_bipolar_board": True,
        "scored": ["cover", "off_caption", "neu_hold"],
        "not_scored": [
            "leak_frac",
            "collapse",
            "pair_odd_cos",
            "minus_overlap",
            "exam_score",
        ],
        "gates": {
            "cover_min": PLUS_COVER_MIN,
            "off_caption_max": PLUS_OFF_MAX,
            "neu_hold_min": PLUS_NEU_HOLD_MIN,
        },
        "recipes": [c["name"] for c in PLUS_NEU_RECIPES],
        "cells": list(PLUS_NEU_CELLS),
        "steps": args.steps,
        "seed": args.seed,
        "helps": verdict,
        "rank": ranked,
        "rows": table,
    }
    (args.out / "metrics.json").write_text(
        json.dumps(blob, indent=2, default=str) + "\n", encoding="utf-8"
    )
    plot_plus_neu_scale(table, args.out / "plus-neu-scale.png")
    write_markdown(table, verdict, ranked, _REPO / "docs" / "lm-plus-neu-exam.md")
    print(f"wrote {args.out}  beats_hold={verdict['beats_plus_on_neu_hold']} keeps_cover={verdict['keeps_plus_cover']}")


if __name__ == "__main__":
    main()
